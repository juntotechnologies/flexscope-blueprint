#!/usr/bin/env node
// Derive drawing/drawing.json (builder config) + drawing/gen/data.js (worker data) from drawing/data.json.
const fs = require('node:fs'), path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'drawing/data.json');

function configDrawing(d) {
  const parts = d.parts.map(function name(p) { return {id: p.id, name: p.name}; });
  return {id: d.id, title: d.title, description: d.description, initialView: d.initialView, parameters: d.parameters, parts};
}

function workerData(data) {
  const byDrawing = {};
  for (const d of data.drawings) byDrawing[d.id] = Object.fromEntries(d.parts.map(function entry(p) { return [p.id, p]; }));
  return {dims: data.dims, parts: byDrawing};
}

function outputs(data) {
  const config = {dependencies: '../node_modules', modelScripts: ['gen/data.js', 'scope.js', 'tip.js'], drawings: data.drawings.map(configDrawing)};
  return {
    'drawing/drawing.json': JSON.stringify(config, null, 2) + '\n',
    'drawing/gen/data.js': '// GENERATED by tools/gen.cjs from drawing/data.json. Do not edit.\nself.ScopeData = ' + JSON.stringify(workerData(data), null, 2) + ';\n'
  };
}

function main(check) {
  const files = outputs(JSON.parse(fs.readFileSync(source, 'utf8')));
  const stale = [];
  for (const [rel, text] of Object.entries(files)) {
    const file = path.join(root, rel);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === text) continue;
    if (check) stale.push(rel);
    else { fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, text); }
  }
  if (stale.length) { console.error(JSON.stringify({event: 'gen.drift', files: stale})); process.exitCode = 1; }
}

main(process.argv.includes('--check'));
